import { spawnSync } from 'child_process'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync
} from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
import {
  CREATURE_SPECIES,
  STAGE_CLIPS,
  assetOutputPath,
  clipGrid,
  frameManifestPath,
  frameManifestTsPath,
  repoRoot
} from './creature-manifest.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const FRAME_SIZE = 192
const prototypeRoot = join(repoRoot, 'assets', 'creature-prototypes')

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function writeJson(path, value) {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`, 'utf8')
}

function pngSize(path) {
  const header = readFileSync(path)
  if (
    header.length < 24 ||
    header.toString('hex', 0, 8) !== '89504e470d0a1a0a' ||
    header.toString('ascii', 12, 16) !== 'IHDR'
  ) {
    throw new Error(`Not a PNG: ${path}`)
  }
  return { width: header.readUInt32BE(16), height: header.readUInt32BE(20) }
}

function actionDir(species, stage, clip) {
  return join(prototypeRoot, species, 'animations', stage, clip)
}

function assertAcceptedAction(species, stage, clip) {
  const dir = actionDir(species, stage, clip)
  const qcPath = join(dir, 'qc.json')
  if (!existsSync(qcPath)) throw new Error(`Missing QC: ${qcPath}`)
  const qc = readJson(qcPath)
  if (qc.passed !== true) throw new Error(`Prototype QC did not pass: ${qcPath}`)

  const expectedFrames = clipGrid(stage, clip).frames
  if (qc.frame_count !== expectedFrames) {
    throw new Error(
      `${species}/${stage}/${clip}: QC has ${qc.frame_count} frames, expected ${expectedFrames}`
    )
  }

  for (let frame = 1; frame <= expectedFrames; frame++) {
    const path = join(dir, `${clip}-${frame}.png`)
    if (!existsSync(path)) throw new Error(`Missing accepted frame: ${path}`)
    const size = pngSize(path)
    if (size.width !== FRAME_SIZE || size.height !== FRAME_SIZE) {
      throw new Error(
        `${species}/${stage}/${clip}-${frame}: ${size.width}x${size.height}, expected ${FRAME_SIZE}x${FRAME_SIZE}`
      )
    }
  }

  return { dir, frames: expectedFrames }
}

function stitch(species, stage, clip, dir) {
  const output = assetOutputPath(species, stage, clip)
  mkdirSync(dirname(output), { recursive: true })
  const result = spawnSync(
    process.env.PYTHON || 'python',
    [
      join(__dirname, 'stitch_sprite_strip.py'),
      '--input-dir',
      dir,
      '--output',
      output,
      '--prefix',
      clip,
      '--frame-size',
      String(FRAME_SIZE)
    ],
    { cwd: repoRoot, stdio: 'inherit' }
  )
  if (result.status !== 0) {
    throw new Error(`Failed to stitch ${species}/${stage}/${clip}`)
  }
}

function writeFrameManifest(manifest) {
  const jsonPath = frameManifestPath()
  mkdirSync(dirname(jsonPath), { recursive: true })
  writeJson(jsonPath, manifest)

  const ts = `// Auto-generated by scripts/promote-creature-prototypes.mjs — do not edit by hand.
import type { CreatureSpecies } from './creatureCharacters'
import { CREATURE_FRAME_SIZE } from './creatureCharacters'

export type CreatureClipEntry = { frameSize: number; frames: number }

export const CREATURE_FRAME_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<
  CreatureSpecies,
  Record<string, Record<string, CreatureClipEntry>>
>

export function creatureFrameSize(
  species: CreatureSpecies,
  stage: string,
  clip: string
): number | undefined {
  return CREATURE_FRAME_MANIFEST[species]?.[stage]?.[clip]?.frameSize
}

export function creatureMaxFrameSize(species: CreatureSpecies, stage: string): number {
  const clips = CREATURE_FRAME_MANIFEST[species]?.[stage]
  if (!clips) return CREATURE_FRAME_SIZE
  const sizes = Object.values(clips).map((entry) => entry.frameSize)
  return sizes.length > 0 ? Math.max(...sizes) : CREATURE_FRAME_SIZE
}
`
  writeFileSync(frameManifestTsPath(), ts, 'utf8')
}

function markRuntimeRegistered() {
  const summaryPath = join(prototypeRoot, 'animation-qc-summary.json')
  const summary = readJson(summaryPath)
  if (summary.passed !== true) {
    throw new Error(`Roster QC summary is not accepted: ${summaryPath}`)
  }
  summary.runtime_registered = true
  writeJson(summaryPath, summary)

  for (const species of CREATURE_SPECIES) {
    for (const stage of Object.keys(STAGE_CLIPS)) {
      const contractPath = join(
        prototypeRoot,
        species,
        'animations',
        stage,
        'anchor-contract.json'
      )
      const contract = readJson(contractPath)
      contract.runtime_registered = true
      writeJson(contractPath, contract)
    }
  }
}

function main() {
  const manifest = {}
  let strips = 0

  for (const species of CREATURE_SPECIES) {
    manifest[species] = {}
    for (const [stage, clips] of Object.entries(STAGE_CLIPS)) {
      manifest[species][stage] = {}
      for (const clip of clips) {
        const accepted = assertAcceptedAction(species, stage, clip)
        stitch(species, stage, clip, accepted.dir)
        manifest[species][stage][clip] = {
          frameSize: FRAME_SIZE,
          frames: accepted.frames
        }
        strips += 1
      }
    }
  }

  writeFrameManifest(manifest)
  markRuntimeRegistered()
  console.log(`Promoted ${strips} accepted prototype strips for ${CREATURE_SPECIES.length} species.`)
}

try {
  main()
} catch (error) {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
}
